#!/usr/bin/env node
/**
 * Produces one self-contained Worker file with the embeddings index inlined,
 * for deploying via the Cloudflare dashboard's browser-based editor instead
 * of the wrangler CLI (e.g. from a phone or tablet with no terminal).
 *
 * The dashboard's Quick Edit only accepts a single script — it can't resolve
 * `import indexData from "./index-data.json"` the way wrangler's bundler
 * does — so this inlines that JSON as a const in its place.
 *
 * Usage: node rag/scripts/bundle-worker.mjs
 * Requires rag/worker/src/index-data.json to already exist
 * (node rag/scripts/build-rag-index.mjs).
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const WORKER_SRC = resolve(root, "rag/worker/src/worker.js");
const INDEX = resolve(root, "rag/worker/src/index-data.json");
const OUT = resolve(root, "rag/worker/dist/worker.bundle.js");

if (!existsSync(INDEX)) {
  console.error("Missing rag/worker/src/index-data.json — run: GEMINI_API_KEY=... node rag/scripts/build-rag-index.mjs");
  process.exit(1);
}

const src = readFileSync(WORKER_SRC, "utf8");
const indexData = readFileSync(INDEX, "utf8");

const IMPORT_LINE = 'import indexData from "./index-data.json";';
if (!src.includes(IMPORT_LINE)) {
  console.error("worker.js no longer has the expected import line — update this script to match.");
  process.exit(1);
}

const bundled =
  `// AUTO-GENERATED by rag/scripts/bundle-worker.mjs — do not hand-edit.\n` +
  `// Paste this whole file into the Cloudflare dashboard's Worker editor (Quick Edit).\n` +
  `// Rebuild after any change to worker.js or the index: node rag/scripts/bundle-worker.mjs\n\n` +
  src.replace(IMPORT_LINE, `const indexData = ${indexData};`);

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, bundled);
// Same bytes under .txt: phones and tablets open that as readable text (with a
// working "select all") instead of downloading it as an unopenable script.
writeFileSync(OUT.replace(/\.js$/, ".txt"), bundled);
console.log(`Wrote ${OUT} and its .txt twin (${(bundled.length / 1024).toFixed(0)} KB) — paste either into the dashboard editor.`);
